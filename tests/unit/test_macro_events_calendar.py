"""Unit tests for ``analytics.macro.calendar`` (BL-724).

Covers:

* Loading the on-disk calendar — must contain >= 500 events.
* :func:`is_in_blackout_window` — returns True inside the window,
  False outside, and only fires for HIGH/MEDIUM events by default.
* Currency resolution — EURUSD reacts to both EUR and USD events;
  ES reacts only to USD events; GBPJPY reacts to both GBP and JPY.
* :func:`get_upcoming_events` — lookahead filter, currency filter,
  impact filter.
* :class:`MacroEvent` validation — timezone-naive inputs are coerced
  to UTC, currency codes are uppercased.
* :class:`MacroCalendar` filters and day lookup.
* :func:`compute_file_sha256` matches the ``file_sha256`` baked in
  the JSON header.

The calendar is regenerated by ``scripts/build_economic_calendar.py``
and is checked in — the tests assert against the on-disk artifact.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime, timedelta
from pathlib import Path

import pytest

from analytics.macro.calendar import (
    ASSET_CURRENCIES,
    DEFAULT_CALENDAR_PATH,
    SCHEMA_VERSION,
    ImpactLevel,
    MacroCalendar,
    MacroEvent,
    compute_file_sha256,
    get_upcoming_events,
    is_in_blackout_window,
)

