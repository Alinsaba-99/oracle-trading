class TestBlackoutWindow:
    @pytest.fixture
    def cal(self) -> MacroCalendar:
        return MacroCalendar.from_json()

    def test_fomc_event_triggers_blackout_for_es(self, cal: MacroCalendar) -> None:
        # FOMC 2024-09-18 18:00 UTC is in the calendar.
        ts = datetime(2024, 9, 18, 18, 0, tzinfo=UTC)
        hit, eid = is_in_blackout_window(ts, "ES", cal)
        assert hit is True
        assert eid is not None
        assert "fomc" in eid.lower()

    def test_outside_window_returns_false(self, cal: MacroCalendar) -> None:
        # 30 minutes before FOMC is outside the default 5-minute window.
        ts = datetime(2024, 9, 18, 17, 20, tzinfo=UTC)
        hit, eid = is_in_blackout_window(ts, "ES", cal)
        assert hit is False
        assert eid is None

    def test_window_5min_before_event(self, cal: MacroCalendar) -> None:
        # 4 minutes before the FOMC = inside 5-min window.
        ts = datetime(2024, 9, 18, 17, 56, tzinfo=UTC)
        hit, _ = is_in_blackout_window(ts, "ES", cal)
        assert hit is True

    def test_window_5min_after_event(self, cal: MacroCalendar) -> None:
        # 4 minutes after the FOMC = inside 5-min window.
        ts = datetime(2024, 9, 18, 18, 4, tzinfo=UTC)
        hit, _ = is_in_blackout_window(ts, "ES", cal)
        assert hit is True

    def test_exact_event_time_is_in_window(self, cal: MacroCalendar) -> None:
        ts = datetime(2024, 9, 18, 18, 0, tzinfo=UTC)
        hit, _ = is_in_blackout_window(ts, "ES", cal)
        assert hit is True

    def test_naive_datetime_coerced_to_utc(self, cal: MacroCalendar) -> None:
        ts = datetime(2024, 9, 18, 18, 0)  # no tzinfo
        hit, _ = is_in_blackout_window(ts, "ES", cal)
        assert hit is True

    def test_eurusd_reacts_to_both_eur_and_usd(self, cal: MacroCalendar) -> None:
        # FOMC (USD) hits EURUSD
        ts_fomc = datetime(2024, 9, 18, 18, 0, tzinfo=UTC)
        hit_usd, eid_usd = is_in_blackout_window(ts_fomc, "EURUSD", cal)
        assert hit_usd is True
        assert "fomc" in eid_usd.lower()  # type: ignore[arg-type]

        # ECB (EUR) hits EURUSD
        ts_ecb = datetime(2024, 9, 12, 13, 45, tzinfo=UTC)
        hit_eur, eid_eur = is_in_blackout_window(ts_ecb, "EURUSD", cal)
        assert hit_eur is True
        assert "ecb" in eid_eur.lower()  # type: ignore[arg-type]

    def test_es_only_reacts_to_usd(self, cal: MacroCalendar) -> None:
        # ECB event should NOT affect ES.
        ts_ecb = datetime(2024, 9, 12, 13, 45, tzinfo=UTC)
        hit, eid = is_in_blackout_window(ts_ecb, "ES", cal)
        assert hit is False
        assert eid is None

    def test_ftse_reacts_to_gbp_not_usd(self, cal: MacroCalendar) -> None:
        # BOE 2024-09-19 12:00 UTC -> FTSE blackout
        ts_boe = datetime(2024, 9, 19, 12, 0, tzinfo=UTC)
        hit_gbp, eid_gbp = is_in_blackout_window(ts_boe, "FTSE", cal)
        assert hit_gbp is True
        assert "boe" in eid_gbp.lower()  # type: ignore[arg-type]

        # FOMC should NOT affect FTSE (FTSE is GBP-only).
        ts_fomc = datetime(2024, 9, 18, 18, 0, tzinfo=UTC)
        hit, _ = is_in_blackout_window(ts_fomc, "FTSE", cal)
        assert hit is False

    def test_gbpjpy_reacts_to_both_gbp_and_jpy(self, cal: MacroCalendar) -> None:
        ts_boe = datetime(2024, 9, 19, 12, 0, tzinfo=UTC)
        hit, _ = is_in_blackout_window(ts_boe, "GBPJPY", cal)
        assert hit is True
        ts_boj = datetime(2024, 9, 20, 3, 0, tzinfo=UTC)
        hit, _ = is_in_blackout_window(ts_boj, "GBPJPY", cal)
        assert hit is True

    def test_currency_argument_works(self, cal: MacroCalendar) -> None:
        # Passing "USD" directly instead of a symbol should work.
        ts = datetime(2024, 9, 18, 18, 0, tzinfo=UTC)
        hit, _ = is_in_blackout_window(ts, "USD", cal)
        assert hit is True

    def test_custom_window_widens_detection(self, cal: MacroCalendar) -> None:
        # 30 minutes before the FOMC — outside default 5m, inside 30m.
        ts = datetime(2024, 9, 18, 17, 30, tzinfo=UTC)
        hit_default, _ = is_in_blackout_window(ts, "ES", cal, window_before_m=5)
        assert hit_default is False
        hit_wide, _ = is_in_blackout_window(ts, "ES", cal, window_before_m=30)
        assert hit_wide is True

    def test_low_impact_does_not_trigger_by_default(self) -> None:
        """Synthetic LOW-impact event must NOT block by default."""
        ev = MacroEvent(
            event_id="low-test",
            event_name="LowImpact",
            currency="USD",
            event_time_utc=datetime(2024, 6, 1, 12, 0, tzinfo=UTC),
            impact_level=ImpactLevel.LOW,
            source="test",
        )
        cal2 = MacroCalendar([ev])
        ts = ev.event_time_utc
        hit, _ = is_in_blackout_window(ts, "ES", cal2)
        assert hit is False

    def test_medium_impact_uses_shorter_window(self) -> None:
        """MEDIUM events trigger with the scaled (2m) window, not the HIGH (5m)."""
        ev = MacroEvent(
            event_id="med-test",
            event_name="MedImpact",
            currency="USD",
            event_time_utc=datetime(2024, 6, 1, 12, 0, tzinfo=UTC),
            impact_level=ImpactLevel.MEDIUM,
            source="test",
        )
        cal2 = MacroCalendar([ev])
        # 1 minute before — inside the MEDIUM scaled window (2m).
        ts_inside = ev.event_time_utc - timedelta(minutes=1)
        hit, _ = is_in_blackout_window(ts_inside, "ES", cal2, window_before_m=5)
        assert hit is True
        # 4 minutes before — outside MEDIUM's 2m window even though inside HIGH's 5m.
        ts_outside = ev.event_time_utc - timedelta(minutes=4)
        hit, _ = is_in_blackout_window(ts_outside, "ES", cal2, window_before_m=5, window_after_m=5)
        assert hit is False

        # Sanity: same event at -4m DOES trigger if we widen the caller window.
        ts_wide = ev.event_time_utc - timedelta(minutes=4)
        hit, _ = is_in_blackout_window(ts_wide, "ES", cal2, window_before_m=10, window_after_m=10)
        # With caller window=10, MEDIUM scale = max(1, round(10*0.4)) = 4.
        # -4m sits exactly on the edge → inclusive → True.
        assert hit is True


