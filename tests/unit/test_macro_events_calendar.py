class TestCalendarLoading:
    def test_schema_version(self) -> None:
        assert SCHEMA_VERSION == "bl724-economic-calendar-v1"

    def test_default_path_exists(self) -> None:
        assert DEFAULT_CALENDAR_PATH.exists(), (
            f"Calendar missing at {DEFAULT_CALENDAR_PATH} — run scripts/build_economic_calendar.py"
        )

    def test_loads_at_least_500_events(self) -> None:
        cal = MacroCalendar.from_json()
        assert len(cal) >= 500, f"only {len(cal)} events, expected ≥500"

    def test_covers_2008_to_2026(self) -> None:
        cal = MacroCalendar.from_json()
        events = cal.events
        assert events[0].event_time_utc.year <= 2008
        assert events[-1].event_time_utc.year >= 2026

    def test_includes_key_event_families(self) -> None:
        cal = MacroCalendar.from_json()
        names = {ev.event_name for ev in cal.events}
        for required in (
            "FOMC Rate Decision",
            "ECB Rate Decision",
            "BOE Rate Decision",
            "Non-Farm Payrolls",
            "CPI m/m",
            "PPI m/m",
            "GDP Advance q/q",
            "Jackson Hole Symposium",
        ):
            assert required in names, f"missing event family: {required}"

    def test_event_ids_are_unique(self) -> None:
        cal = MacroCalendar.from_json()
        ids = [ev.event_id for ev in cal.events]
        assert len(ids) == len(set(ids))

    def test_each_event_has_source_sha256(self) -> None:
        cal = MacroCalendar.from_json()
        for ev in cal.events:
            assert ev.source_sha256, f"{ev.event_id} missing source_sha256"
            assert len(ev.source_sha256) == 64

    def test_empty_calendar_helper(self) -> None:
        assert len(MacroCalendar.empty()) == 0

    def test_from_json_missing_file_raises(self, tmp_path: Path) -> None:
        with pytest.raises(FileNotFoundError):
            MacroCalendar.from_json(tmp_path / "nope.json")

    def test_from_json_invalid_schema_raises(self, tmp_path: Path) -> None:
        bad = tmp_path / "bad.json"
        bad.write_text(json.dumps({"oops": []}))
        with pytest.raises(ValueError, match="missing 'events' key"):
            MacroCalendar.from_json(bad)

    def test_file_sha256_header_matches_disk(self) -> None:
        """The baked-in ``file_sha256`` matches the on-disk bytes."""
        # ``compute_file_sha256`` hashes the actual on-disk bytes; the
        # build script bakes a sha256 over the canonical (compact) form of
        # the document — they are derived from the same underlying dict so
        # the test asserts both end-to-end values match the helper.
        raw = json.loads(DEFAULT_CALENDAR_PATH.read_text())
        assert "file_sha256" in raw
        assert raw["file_sha256"] == compute_file_sha256(DEFAULT_CALENDAR_PATH)


