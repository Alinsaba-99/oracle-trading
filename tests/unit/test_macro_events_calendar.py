class TestCalendarFilters:
    @pytest.fixture
    def cal(self) -> MacroCalendar:
        return MacroCalendar.from_json()

    def test_filter_by_currency(self, cal: MacroCalendar) -> None:
        usd = cal.filter(currency="USD")
        eur = cal.filter(currency="EUR")
        assert usd and eur
        assert all(e.currency == "USD" for e in usd)
        assert all(e.currency == "EUR" for e in eur)
        assert len(usd) > len(eur)

    def test_filter_by_impact(self, cal: MacroCalendar) -> None:
        high = cal.filter(impact=ImpactLevel.HIGH)
        med = cal.filter(impact=ImpactLevel.MEDIUM)
        assert high
        assert all(e.impact_level == ImpactLevel.HIGH for e in high)
        assert all(e.impact_level == ImpactLevel.MEDIUM for e in med)

    def test_contains(self, cal: MacroCalendar) -> None:
        some_id = cal.events[0].event_id
        assert some_id in cal
        assert "does-not-exist" not in cal

    def test_get_returns_none_for_unknown(self, cal: MacroCalendar) -> None:
        assert cal.get("nope") is None
        assert cal.get(cal.events[0].event_id) is not None

    def test_events_on_specific_day(self, cal: MacroCalendar) -> None:
        # 2024-09-18 is a known FOMC day.
        evs = cal.events_on("2024-09-18")
        names = [e.event_name for e in evs]
        assert "FOMC Rate Decision" in names

    def test_events_on_returns_empty_for_unknown_day(self, cal: MacroCalendar) -> None:
        assert cal.events_on("1999-01-01") == []


