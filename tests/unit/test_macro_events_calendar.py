class TestMacroEventModel:
    def test_naive_datetime_coerced_to_utc(self) -> None:
        ev = MacroEvent(
            event_id="x",
            event_name="x",
            currency="usd",
            event_time_utc=datetime(2024, 9, 18, 18, 0),
            impact_level=ImpactLevel.HIGH,
            source="s",
        )
        assert ev.event_time_utc.tzinfo is not None
        assert ev.event_time_utc.tzinfo == UTC
        assert ev.currency == "USD"

    def test_currency_normalized_upper(self) -> None:
        ev = MacroEvent(
            event_id="x",
            event_name="x",
            currency="eur",
            event_time_utc=datetime(2024, 1, 1, tzinfo=UTC),
            impact_level=ImpactLevel.MEDIUM,
            source="s",
        )
        assert ev.currency == "EUR"

    def test_event_is_frozen(self) -> None:
        ev = MacroEvent(
            event_id="x",
            event_name="x",
            currency="USD",
            event_time_utc=datetime(2024, 1, 1, tzinfo=UTC),
            impact_level=ImpactLevel.HIGH,
            source="s",
        )
        with pytest.raises(ValueError, match="frozen"):
            ev.event_name = "y"  # type: ignore[misc]


