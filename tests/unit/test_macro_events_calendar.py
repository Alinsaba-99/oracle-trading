class TestUpcomingEvents:
    @pytest.fixture
    def cal(self) -> MacroCalendar:
        return MacroCalendar.from_json()

    def test_lookahead_24h_finds_fomc(self, cal: MacroCalendar) -> None:
        # Look-ahead starting 1h before a known FOMC.
        ts = datetime(2024, 9, 18, 17, 0, tzinfo=UTC)
        events = get_upcoming_events(ts, cal, lookahead_hours=24)
        names = [e.event_name for e in events]
        assert "FOMC Rate Decision" in names

    def test_lookahead_excludes_past(self, cal: MacroCalendar) -> None:
        # Starting AFTER the FOMC — should NOT include it.
        ts = datetime(2024, 9, 18, 19, 0, tzinfo=UTC)
        events = get_upcoming_events(ts, cal, lookahead_hours=24)
        for ev in events:
            assert ev.event_time_utc >= ts

    def test_currency_filter(self, cal: MacroCalendar) -> None:
        ts = datetime(2024, 9, 1, 0, 0, tzinfo=UTC)
        events = get_upcoming_events(ts, cal, lookahead_hours=24 * 30, currency="EUR")
        assert events
        for ev in events:
            assert ev.currency == "EUR"

    def test_impact_filter(self, cal: MacroCalendar) -> None:
        ts = datetime(2024, 9, 1, 0, 0, tzinfo=UTC)
        high_only = get_upcoming_events(ts, cal, lookahead_hours=24 * 30, impact=ImpactLevel.HIGH)
        assert high_only
        for ev in high_only:
            assert ev.impact_level == ImpactLevel.HIGH

    def test_impact_tuple_filter(self, cal: MacroCalendar) -> None:
        ts = datetime(2024, 9, 1, 0, 0, tzinfo=UTC)
        events = get_upcoming_events(
            ts, cal, lookahead_hours=24 * 30, impact=(ImpactLevel.HIGH, ImpactLevel.MEDIUM)
        )
        assert events
        for ev in events:
            assert ev.impact_level in {ImpactLevel.HIGH, ImpactLevel.MEDIUM}

    def test_returns_empty_when_window_empty(self, cal: MacroCalendar) -> None:
        # Far-future window unlikely to contain anything.
        ts = datetime(2030, 1, 1, 0, 0, tzinfo=UTC)
        events = get_upcoming_events(ts, cal, lookahead_hours=1)
        assert events == []


